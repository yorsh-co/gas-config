/**
 * Generates `src/web/gas-config.fonts.css`, which inlines the Yorsh brand
 * typefaces as base64 `@font-face` rules. HtmlService cannot serve static
 * files, so the fonts must travel inside the page. See docs/adr/0001.
 *
 * Usage: `node scripts/build-fonts.js` writes the file;
 * `node scripts/build-fonts.js --check` exits 1 when the file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = `${ROOT}src/web/gas-config.fonts.css`;

const UNICODE_RANGE =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC,\n' +
  '    U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212,\n' +
  '    U+2215, U+FEFF, U+FFFD';

const FACES = [
  {
    family: 'Space Grotesk',
    weight: '300 700',
    file: 'space-grotesk-latin-wght-normal.woff2',
  },
  {
    family: 'DM Sans',
    weight: '100 1000',
    file: 'dm-sans-latin-wght-normal.woff2',
  },
];

const HEADER = `/*
 * Generated by scripts/build-fonts.js. Do not edit.
 * Space Grotesk and DM Sans are (c) their authors, licensed under the
 * SIL Open Font License 1.1. See src/web/fonts/.
 */
`;

/**
 * Builds the full contents of the fonts stylesheet.
 * @returns {string} CSS text with LF line endings and a trailing newline.
 */
function render() {
  const faces = FACES.map(({ family, weight, file }) => {
    const data = readFileSync(`${ROOT}src/web/fonts/${file}`).toString(
      'base64',
    );
    return `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('data:font/woff2;base64,${data}') format('woff2');
  unicode-range:
    ${UNICODE_RANGE};
}
`;
  });
  return `${HEADER}\n${faces.join('\n')}`;
}

const css = render();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // A missing file counts as stale.
  }
  if (current !== css) {
    console.error('gas-config.fonts.css is stale. Run `npm run build:fonts`.');
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, css);
}
